#!/usr/bin/env python3
"""Check the Xcode project for internal consistency.

This project is written and edited on Linux and has never been opened
in Xcode, so this script is the first line of defence before CI:

- every PBXBuildFile points at a PBXFileReference that exists;
- every file reference with a group-relative path resolves to a real
  file on disk (the one exception is extension/dist, which is
  generated by `npm run build` and rebuilt by the "Build Web
  Extension" script phase — a missing dist is a warning, not an error);
- every group child, build-phase file, entitlements path and scheme
  target reference is valid;
- every Swift source file on disk is actually compiled by the targets
  that need it (no orphan files, no missing files);
- the Swift sources respect the project's deployment targets
  (iOS 15.0 / macOS 12.0, Swift 5.0 language mode): no `if let`
  shorthand, no NavigationStack / ViewThatFits / .fontDesign /
  .scrollContentBackground (all iOS 16+).

Usage: python3 scripts/check-xcode-project.py
Exits non-zero when any check fails.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PBXPROJ = ROOT / "xcode" / "OpenMonkey.xcodeproj" / "project.pbxproj"
SCHEME = (
    ROOT / "xcode" / "OpenMonkey.xcodeproj" / "xcshareddata" / "xcschemes"
    / "OpenMonkey.xcscheme"
)

errors: list[str] = []
warnings: list[str] = []


def error(message: str) -> None:
    errors.append(message)


def warn(message: str) -> None:
    warnings.append(message)


def main() -> int:
    text = PBXPROJ.read_text()

    # --- Parse the object graph (good enough for a hand-written file). ---
    # fileRef id -> (comment, body)
    file_refs: dict[str, str] = {}
    for match in re.finditer(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{isa = PBXFileReference; ([^}]*)\};",
        text,
    ):
        file_refs[match.group(1)] = match.group(3)

    build_files: dict[str, str] = {}
    for match in re.finditer(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{isa = PBXBuildFile; ([^}]*)\};",
        text,
    ):
        build_files[match.group(1)] = match.group(3)

    groups: dict[str, list[str]] = {}
    for match in re.finditer(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{\s*isa = PBXGroup;\s*children = \((.*?)\);\s*"
        r"(?:name = ([^\n]+?);|path = ([^\n]+?);)",
        text,
        re.DOTALL,
    ):
        groups[match.group(1)] = re.findall(r"(\w{24}) /\*", match.group(3))

    # --- 1. Build files point at real file references. ---
    for build_id, body in build_files.items():
        ref = re.search(r"fileRef = (\w{24})", body)
        if not ref:
            error(f"PBXBuildFile {build_id} has no fileRef")
        elif ref.group(1) not in file_refs:
            error(f"PBXBuildFile {build_id} points at missing fileRef {ref.group(1)}")

    # --- 2. Group children exist. ---
    all_ids = set(file_refs) | set(groups)
    for group_id, children in groups.items():
        for child in children:
            if child not in all_ids:
                error(f"Group {group_id} lists unknown child {child}")

    # --- 3. Resolve group-relative paths to disk. ---
    # Group path map, by group id (from the project file).
    group_paths: dict[str, Path] = {}
    main_group = re.search(
        r"mainGroup = (\w{24})", text
    )
    assert main_group is not None
    group_paths[main_group.group(1)] = ROOT / "xcode"
    for match in re.finditer(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{\s*isa = PBXGroup;\s*children = \(.*?\);\s*"
        r"path = ([^\n]+?);\s*sourceTree = ",
        text,
        re.DOTALL,
    ):
        group_paths[match.group(1)] = Path(match.group(3).strip())

    def resolve_group(group_id: str) -> Path:
        """The on-disk directory of a group, walking up to the main group."""
        # Groups in this project are one level deep under the main group,
        # so a flat lookup is enough; the main group itself is xcode/.
        if group_id in group_paths and group_paths[group_id].is_absolute():
            return group_paths[group_id]
        rel = group_paths.get(group_id)
        if rel is None:
            return ROOT / "xcode"
        return ROOT / "xcode" / rel

    # Which group owns each file reference?
    owner: dict[str, str] = {}
    for group_id, children in groups.items():
        for child in children:
            if child in file_refs:
                owner[child] = group_id

    for ref_id, body in file_refs.items():
        path_match = re.search(r"path = ([^;]+);", body)
        tree_match = re.search(r"sourceTree = ([^;]+);", body)
        if not path_match or not tree_match:
            continue
        source_tree = tree_match.group(1).strip().strip('"')
        if source_tree == "BUILT_PRODUCTS_DIR" or source_tree == "SDKROOT":
            continue  # generated products / system frameworks
        if source_tree != "<group>":
            error(f"FileRef {ref_id} has unexpected sourceTree {source_tree}")
            continue
        group_id = owner.get(ref_id)
        if group_id is None:
            error(f"FileRef {ref_id} is not in any group")
            continue
        disk = resolve_group(group_id) / path_match.group(1).strip().strip('"')
        if not disk.exists():
            if disk.name == "dist":
                warn(f"{disk} is missing — generated by `npm run build` "
                     "(the 'Build Web Extension' script phase rebuilds it)")
            else:
                error(f"FileRef {ref_id} points at missing file: {disk}")

    # --- 4. Entitlements paths in build configs resolve. ---
    for match in re.finditer(r"CODE_SIGN_ENTITLEMENTS = ([^;]+);", text):
        ent = ROOT / "xcode" / match.group(1).strip()
        if not ent.exists():
            error(f"CODE_SIGN_ENTITLEMENTS points at missing file: {ent}")

    # --- 5. Every Swift file on disk is compiled by the right targets. ---
    sources_phases: dict[str, list[str]] = {}
    for match in re.finditer(
        r"(\w{24}) /\* Sources \*/ = \{\s*isa = PBXSourcesBuildPhase;\s*"
        r"buildActionMask = \d+;\s*files = \((.*?)\);",
        text,
        re.DOTALL,
    ):
        sources_phases[match.group(1)] = re.findall(r"(\w{24}) /\*", match.group(2))

    # Map phase id -> target name via the PBXNativeTarget blocks.
    phase_target: dict[str, str] = {}
    for target in re.finditer(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{\s*isa = PBXNativeTarget;[^}]*?buildPhases = \((.*?)\);",
        text,
        re.DOTALL,
    ):
        for phase_ref in re.findall(r"(\w{24}) /\*", target.group(3)):
            phase_target[phase_ref] = target.group(2)

    compiled: dict[str, set[str]] = {}
    for phase_id, build_ids in sources_phases.items():
        target = phase_target.get(phase_id, phase_id)
        files = set()
        for build_id in build_ids:
            body = build_files.get(build_id, "")
            ref = re.search(r"fileRef = (\w{24})", body)
            if ref:
                files.add(ref.group(1))
        compiled[target] = files

    disk_swift = {
        p.name: p
        for p in list((ROOT / "xcode" / "App").glob("*.swift"))
        + list((ROOT / "xcode" / "Shared").glob("*.swift"))
    }
    ref_by_name = {}
    for ref_id, body in file_refs.items():
        path_match = re.search(r"path = ([^;]+);", body)
        if path_match:
            ref_by_name[path_match.group(1).strip().strip('"')] = ref_id

    for name in sorted(disk_swift):
        ref_id = ref_by_name.get(name)
        if ref_id is None:
            error(f"{name} exists on disk but has no PBXFileReference")
            continue
        for target in ("OpenMonkey", "OpenMonkey-macOS"):
            if ref_id not in compiled.get(target, set()):
                error(f"{name} is not in {target}'s Sources phase")
    # The extension target needs Shared/ + its handler, not App/.
    ext_files = compiled.get("OpenMonkeyExtension", set())
    for name in ("AppGroup.swift", "ScriptStore.swift", "MetadataParser.swift",
                 "SafariWebExtensionHandler.swift"):
        if ref_by_name.get(name) not in ext_files:
            error(f"{name} is not in OpenMonkeyExtension's Sources phase")

    # --- 6. Resources phases carry the assets and the web extension. ---
    resources_phases: dict[str, list[str]] = {}
    for match in re.finditer(
        r"(\w{24}) /\* Resources \*/ = \{\s*isa = PBXResourcesBuildPhase;\s*"
        r"buildActionMask = \d+;\s*files = \((.*?)\);",
        text,
        re.DOTALL,
    ):
        resources_phases[match.group(1)] = re.findall(r"(\w{24}) /\*", match.group(2))

    def resource_names(phase_id: str) -> set[str]:
        names = set()
        for build_id in resources_phases.get(phase_id, []):
            body = build_files.get(build_id, "")
            ref = re.search(r"fileRef = (\w{24})", body)
            if ref and ref.group(1) in file_refs:
                path_match = re.search(
                    r"path = ([^;]+);", file_refs[ref.group(1)])
                if path_match:
                    names.add(path_match.group(1).strip().strip('"'))
        return names

    for phase_id, build_ids in resources_phases.items():
        target = phase_target.get(phase_id, phase_id)
        names = resource_names(phase_id)
        if target in ("OpenMonkey", "OpenMonkey-macOS"):
            if "Assets.xcassets" not in names:
                error(f"{target}'s Resources phase is missing Assets.xcassets")
        if target == "OpenMonkeyExtension" and "dist" not in names:
            error("OpenMonkeyExtension's Resources phase is missing the dist folder")

    # --- 7. The shared scheme points at a real target. ---
    scheme_text = SCHEME.read_text()
    blueprint = re.search(r'BlueprintIdentifier = "(\w+)"', scheme_text)
    target_ids = re.findall(
        r"(\w{24}) /\* ([^\n]+?) \*/ = \{\s*isa = PBXNativeTarget;", text)
    target_names = {tid: name for tid, name in target_ids}
    if not blueprint:
        error("Scheme has no BlueprintIdentifier")
    elif blueprint.group(1) not in target_names:
        error(f"Scheme points at unknown target {blueprint.group(1)}")
    elif target_names[blueprint.group(1)] != "OpenMonkey":
        error("Scheme does not build OpenMonkey")

    # --- 8. Asset catalogue contents resolve. ---
    catalog = ROOT / "xcode" / "App" / "Assets.xcassets"
    for contents_path in catalog.rglob("Contents.json"):
        data = json.loads(contents_path.read_text())
        for image in data.get("images", []):
            filename = image.get("filename")
            if filename and not (contents_path.parent / filename).exists():
                error(f"AppIcon references missing image {filename}")

    # --- 9. Swift deployment-target hygiene (iOS 15 / Swift 5.0). ---
    # Plus the v0.5.1 layout guard: no fixed pill-clearance constant
    # may come back — the clearance comes from the layout flow (the
    # pill is the bottom child of the root VStack), never a constant.
    # And the v0.5.2 guard: the root VStack MUST force-fill the window
    # (.frame(maxWidth: .infinity, maxHeight: .infinity)) — without it
    # the root sized to its children (~589pt) and SwiftUI centred it
    # vertically in the 926pt window, which is exactly what Aaron's
    # 19:11 real-device shot showed. Removing that frame re-breaks
    # every screen at once.
    app_source = (ROOT / "xcode" / "App" / "OpenMonkeyApp.swift").read_text()
    if ".frame(maxWidth: .infinity, maxHeight: .infinity)" not in app_source:
        error("OpenMonkeyApp.swift lost the root fill frame (v0.5.2: the root VStack must force-fill the window)")

    # --- 10. Launch screen (v0.5.3): the app must declare a launch
    # storyboard, or iOS does not give it a native full-screen window
    # (v0.5.2's simulator screenshot showed the app in a ~642pt-tall
    # band centred on the 926pt screen despite the forced-fill root).
    storyboard = ROOT / "xcode" / "App" / "LaunchScreen.storyboard"
    if not storyboard.exists():
        error("xcode/App/LaunchScreen.storyboard is missing (v0.5.3)")
    pbxproj = (ROOT / "xcode" / "OpenMonkey.xcodeproj" / "project.pbxproj").read_text()
    if "LaunchScreen.storyboard" not in pbxproj:
        error("project.pbxproj does not reference LaunchScreen.storyboard (v0.5.3)")
    if "INFOPLIST_KEY_UILaunchStoryboardName = LaunchScreen" not in pbxproj:
        error("project.pbxproj does not set INFOPLIST_KEY_UILaunchStoryboardName (v0.5.3)")
    forbidden = [
        (r"if let \w+ \{", "`if let` shorthand (Swift 5.7+)"),
        (r"NavigationStack", "NavigationStack (iOS 16+)"),
        (r"ViewThatFits", "ViewThatFits (iOS 16+)"),
        (r"\.fontDesign\(", ".fontDesign (iOS 16+)"),
        (r"\.scrollContentBackground\(", ".scrollContentBackground (iOS 16+)"),
        (r"NavigationSplitView", "NavigationSplitView (iOS 16+)"),
        (r"tabBarClearance", "fixed pill clearance (v0.5.1: use layout flow)"),
    ]
    for swift_path in sorted(
        list((ROOT / "xcode" / "App").glob("*.swift"))
        + list((ROOT / "xcode" / "Shared").glob("*.swift"))
        + list((ROOT / "xcode" / "Extension").glob("*.swift"))
    ):
        source = swift_path.read_text()
        for pattern, label in forbidden:
            if re.search(pattern, source):
                error(f"{swift_path.relative_to(ROOT)} uses {label}")

    for warning in warnings:
        print(f"warning: {warning}")
    for message in errors:
        print(f"error: {message}")
    if errors:
        print(f"\n{len(errors)} error(s), {len(warnings)} warning(s)")
        return 1
    print(f"Xcode project OK ({len(warnings)} warning(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
