const STRINGS: Record<Language, Record<I18nKey, string>> = { en, zh };

/** All keys (English is the reference; zh must carry the same set). */
export function i18nKeys(): I18nKey[] {
  return Object.keys(en) as I18nKey[];
}

/** Resolve the effective UI language: an explicit zh/en setting wins;
 * "system" (or a missing/unknown setting) follows the browser language
 * — any zh* locale is Chinese, everything else is English. */
export function resolveLanguage(
  setting: LanguageSetting | string | undefined | null,
  navigatorLanguage?: string,
): Language {
  if (setting === 'zh' || setting === 'en') return setting;
  const nav =
    typeof navigatorLanguage === 'string'
      ? navigatorLanguage
      : typeof navigator !== 'undefined'
        ? navigator.language
        : '';
  return (nav ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** Look up one string, interpolating {name} placeholders from vars. */
export function translate(
  key: I18nKey,
  lang: Language,
  vars?: Record<string, string | number>,
): string {
  let text: string = STRINGS[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Apply the static strings in the markup: elements carry
 * data-i18n="<key>" (text), data-i18n-placeholder="<key>"
 * (input placeholder), or data-i18n-aria-label="<key>" (aria-label).
 * Dynamic strings built in code use translate() directly. */
export function applyStaticStrings(root: ParentNode, lang: Language): void {
  const apply = (attr: string, set: (node: HTMLElement, value: string) => void): void => {
    root.querySelectorAll<HTMLElement>(`[${attr}]`).forEach((node) => {
      const key = node.getAttribute(attr);
      if (key && key in en) set(node, translate(key as I18nKey, lang));
    });
  };
  apply('data-i18n', (node, value) => {
    node.textContent = value;
  });
  apply('data-i18n-placeholder', (node, value) => {
    node.setAttribute('placeholder', value);
  });
  apply('data-i18n-aria-label', (node, value) => {
    node.setAttribute('aria-label', value);
  });
}
